WHITE = "#e6e6e6"    # 보조 강조
RED = "#ff6b6b"      # 주의


def _wrap(body: str) -> str:
    return f'<div class="j6-guide">{body}</div>'


def _line(label: str, text: str, color: str = BLUE) -> str:
    return (
        f'<span style="color:{color}">{label}</span> '
        f'<span style="color:{GRAY}">{text}</span><br>'
    )


